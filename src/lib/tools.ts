export function getToolBySlug(slug: string): Tool | undefined {
  return tools.find((t) => t.slug === slug);
}

export function searchTools(query: string): Tool[] {
  const q = query.trim().toLowerCase();
  if (!q) return tools;
  return tools
    .map((tool, index) => ({
      tool,
      index,
      name: tool.name.toLowerCase(),
      shortName: tool.shortName.toLowerCase(),
      searchableText: [tool.name, tool.shortName, tool.description, ...tool.synonyms]
        .join(' ')
        .toLowerCase(),
    }))
    .filter(({ name, shortName, searchableText }) =>
      q.length === 1
        ? name.startsWith(q) || shortName.startsWith(q)
        : searchableText.includes(q),
    )
    .sort((a, b) => {
      const aStartsWithQuery = a.name.startsWith(q) || a.shortName.startsWith(q);
      const bStartsWithQuery = b.name.startsWith(q) || b.shortName.startsWith(q);
      if (aStartsWithQuery !== bStartsWithQuery) return aStartsWithQuery ? -1 : 1;
      return a.name.localeCompare(b.name) || a.index - b.index;
    })
    .map(({ tool }) => tool);
}

